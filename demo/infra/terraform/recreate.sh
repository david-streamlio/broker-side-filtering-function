#!/usr/bin/env bash
#
# One-shot bring-up for the stock-quote demo's SN Cloud infrastructure.
#
# Phases:
#   0  pre-flight (env + tooling)
#   1  status check (is the cluster already up?)
#   2  Terraform Step A — instance, cluster, SAs, apikeys
#   3  wait for cluster admin endpoint
#   4  clear stale pulsar-provider state (after first apply)
#   5  Terraform Step B — tenant, namespaces, topics, permissions
#   6  export SA tokens to disk (app.token, orchestrator-function.token)
#   7  upload selector-filter NAR + deploy orchestrator function
#   8  verify
#
# Required env:
#   ORG               SN Cloud organization id (e.g. o-mj3r8)
#   SELECTOR_REPO     GitHub repo to download orchestrator + filter NARs from
#                     (default: david-streamlio/broker-side-filtering-function)
#   SELECTOR_REL      Release tag (default: v1.1.0)
#
# Optional env:
#   PULSAR_TOKEN      pre-minted instance-scoped superuser JWT for Step B.
#                     Bypasses the key-file mint — required on instances whose
#                     per-client Auth0 client-grant was never provisioned.
#                     Get one as a Super Admin:
#                       snctl -O $ORG auth get-token <cluster>-instance --login
#   PULSAR_IMAGE      pulsar-admin Docker image for Phase 7 (default:
#                     apachepulsar/pulsar:4.2.1). No host pulsar-admin needed.
#   PULSAR_CLUSTER    cluster name (default: stock-demo — matches variables.tf)
#   RESET=1           undeploy the orchestrator before re-running Phase 7

set -euo pipefail

# ── Helpers ───────────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
section() { echo -e "\n${BLUE}=== $* ===${NC}"; }
ok()      { echo -e "  ${GREEN}✓${NC} $*"; }
warn()    { echo -e "  ${YELLOW}!${NC} $*"; }
fail()    { echo -e "  ${RED}✗${NC} $*"; exit 1; }
elapsed() { local label="$1" start="$2"; printf "  ${BLUE}⏱${NC}  %s: %ds\n" "$label" $(( $(date +%s) - start )); }

TF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$TF_DIR"

PULSAR_IMAGE="${PULSAR_IMAGE:-apachepulsar/pulsar:4.2.1}"
PULSAR_CLUSTER="${PULSAR_CLUSTER:-stock-demo}"
SELECTOR_REPO="${SELECTOR_REPO:-david-streamlio/broker-side-filtering-function}"
SELECTOR_REL="${SELECTOR_REL:-v1.1.0}"

# ── Phase 0: Pre-flight ───────────────────────────────────────────────────────
section "Phase 0 — Pre-flight"

[[ -n "${ORG:-}" ]]                             || fail "ORG env var not set — export ORG=<your-sn-cloud-org-id>"
# var.organization has no default (forces an explicit org). Map ORG -> the
# terraform var here so neither the Phase-2 targeted apply nor the Phase-5
# Step B apply prompts interactively (breaks unattended runs).
export TF_VAR_organization="$ORG"
[[ -f "$TF_DIR/streamnative-key.json" ]]        || fail "streamnative-key.json not found in $TF_DIR (download from SN Cloud console)"
command -v docker > /dev/null 2>&1              || fail "docker not found — Phase 7 runs pulsar-admin via $PULSAR_IMAGE (no host pulsar-admin needed)"
command -v curl   > /dev/null 2>&1              || fail "curl not found"
command -v terraform > /dev/null 2>&1           || fail "terraform not found"
command -v python3   > /dev/null 2>&1           || fail "python3 not found (used to parse terraform JSON output)"

APP_TOKEN=""
OF_TOKEN=""
[[ -f "$TF_DIR/app.token" ]]                   && APP_TOKEN=$(cat "$TF_DIR/app.token")
[[ -f "$TF_DIR/orchestrator-function.token" ]] && OF_TOKEN=$(cat "$TF_DIR/orchestrator-function.token")

ok "All required artifacts present (SA tokens will be generated by Phase 2 if missing)"

# ── Phase 1: Status check ─────────────────────────────────────────────────────
section "Phase 1 — Status check"
PHASE1_START=$(date +%s)

CLUSTER_UP=false
ADMIN_URL=$(terraform output -raw pulsar_web_service_url 2>/dev/null || true)

if [[ -n "$ADMIN_URL" && -n "$OF_TOKEN" ]] && curl -sf --max-time 10 "$ADMIN_URL/admin/v2/clusters" \
    -H "Authorization: Bearer $OF_TOKEN" > /dev/null 2>&1; then
  CLUSTER_UP=true
  ok "Cluster responding at $ADMIN_URL"
elif [[ -z "$OF_TOKEN" ]]; then
  warn "No SA tokens yet — first run, will bootstrap via Terraform Step A"
else
  warn "Cluster not responding — will recreate"
fi
elapsed "Status check" $PHASE1_START

# ── Phase 2: Terraform Step A ─────────────────────────────────────────────────
if [[ "$CLUSTER_UP" == "false" ]]; then
  section "Phase 2 — Terraform Step A (instance, cluster, SAs, apikeys)"
  PHASE2_START=$(date +%s)

  echo "  Running terraform init..."
  terraform init -input=false 2>&1 | tail -5 || fail "terraform init failed"

  TF_TARGETS=(
    -target=streamnative_pulsar_instance.stock_demo
    -target=streamnative_pulsar_cluster.stock_demo
    -target=data.streamnative_pulsar_instance.stock_demo
    -target=data.streamnative_pulsar_cluster.stock_demo
    -target=streamnative_service_account.stock_demo_app
    -target=streamnative_service_account.orchestrator_function
    -target=streamnative_service_account_binding.stock_demo_app
    -target=streamnative_service_account_binding.orchestrator_function
    -target=streamnative_apikey.stock_demo_app
    -target=streamnative_apikey.orchestrator_function
    -target=streamnative_rolebinding.stock_demo_app_consumer_group_reader
    -target=streamnative_rolebinding.stock_demo_app_namespace_operator
  )

  # Serverless instance/cluster provisioning takes ~10-15 min. The provider
  # returns CONTINUE_RETRY_READ_PULSAR_INSTANCE / "cluster not found" fast
  # (it exhausts its own internal poll budget and errors rather than
  # blocking), so each attempt is short — the loop, not the provider, is
  # what actually waits out provisioning. 30 attempts * 60s = ~30 min ceiling.
  attempt=1
  until terraform apply -auto-approve "${TF_TARGETS[@]}" 2>&1; do
    warn "Instance/cluster still provisioning (attempt $attempt/30) — retrying in 60s..."
    attempt=$(( attempt + 1 ))
    [[ $attempt -gt 30 ]] && fail "Instance/cluster not queryable after 30 attempts (~30 min) — check the SN Cloud console for the stock-demo instance state"
    sleep 60
  done
  elapsed "Terraform Step A" $PHASE2_START
  ok "Cluster + service accounts + apikeys created"

  # Save API key tokens to files for later phases.
  terraform output -json apikey_tokens | python3 -c "
import sys, json
tokens = json.load(sys.stdin)
for name, token in tokens.items():
    fname = name.replace('_', '-') + '.token'
    open(fname, 'w').write(token)
    print(f'  wrote {fname}')
"
  APP_TOKEN=$(cat "$TF_DIR/app.token")
  OF_TOKEN=$(cat "$TF_DIR/orchestrator-function.token")

  # ── Phase 3: Wait for cluster ──────────────────────────────────────────────
  section "Phase 3 — Wait for cluster admin endpoint"
  PHASE3_START=$(date +%s)
  ADMIN_URL=$(terraform output -raw pulsar_web_service_url)
  echo "  URL: $ADMIN_URL"
  until curl -sf --max-time 5 "$ADMIN_URL/admin/v2/clusters" \
      -H "Authorization: Bearer $OF_TOKEN" > /dev/null 2>&1; do
    printf "."
    sleep 5
  done
  echo ""
  elapsed "Cluster ready" $PHASE3_START
  ok "Cluster responding"

  # ── Phase 4: Clear stale Pulsar terraform state ────────────────────────────
  section "Phase 4 — Clear stale Pulsar state"
  PULSAR_RESOURCES=(
    pulsar_tenant.stock_demo
    pulsar_namespace.filtering
    pulsar_topic.stock_quotes
    pulsar_topic.filter_requests
    pulsar_topic.orchestrator_state
    pulsar_permission_grant.app_public_default
    pulsar_permission_grant.app_filter_requests
    pulsar_permission_grant.orchestrator_filter_deploy
    pulsar_permission_grant.orchestrator_consume_control
    pulsar_permission_grant.orchestrator_state_consume
    pulsar_permission_grant.orchestrator_state_produce
    pulsar_permission_grant.orchestrator_consume_source
    pulsar_permission_grant.orchestrator_produce_output
  )
  for r in "${PULSAR_RESOURCES[@]}"; do
    terraform state rm "$r" 2>/dev/null && echo "  removed: $r" || echo "  skipped: $r"
  done
  ok "Stale Pulsar state cleared"
else
  ok "Cluster already up — skipping Phases 2-4 (provisioning + stale-state clear)"
fi

# ── Phase 5: Terraform Step B ────────────────────────────────────────────────
# ALWAYS runs — deliberately OUTSIDE the CLUSTER_UP gate. Step B is fully
# idempotent (`terraform apply` reconciles tenant/namespaces/topics/permissions
# and is a no-op when they already exist). Keeping it gated meant a partial run
# that died after Phase 4 but before Step B left the cluster
# provisioned-but-empty, and the re-run then skipped Step B entirely because
# the cluster now reports "up".
section "Phase 5 — Terraform Step B (tenant, namespaces, topics, permissions)"
PHASE5_START=$(date +%s)

# Instance name is deterministic: main.tf sets name = "${var.cluster_name}-instance".
# Don't round-trip through `terraform output -json pulsar_instance` — a targeted
# Phase-2 apply doesn't persist that output, so it returns {} and the old
# python parse died with KeyError: 'value'.
INSTANCE_NAME="${TF_VAR_cluster_name:-stock-demo}-instance"

export TF_VAR_pulsar_web_service_url="$ADMIN_URL"

# Step B needs an instance-scoped superuser token. Two ways to get one:
#
#   1. PULSAR_TOKEN env override (operator-supplied). Use when the key-file
#      M2M mint can't work: SN Cloud registers each instance as its own Auth0
#      resource server (urn:sn:pulsar:$ORG:$INSTANCE), and the SA's OAuth2
#      *client* needs a per-instance "client-grant" to get a token for it.
#      That grant is provisioned out-of-band and is NOT created by Super
#      Admin status, by the service-account/cluster binding, or by anything
#      in this script — a brand-new instance simply has no grant for this
#      client, so the key-file mint returns "client is not authorized to
#      access resource server ... create a client-grant". The fix that works
#      without that grant: mint interactively as a Super Admin through
#      snctl's own first-party client —
#        export PULSAR_TOKEN=$(snctl -O $ORG auth get-token $INSTANCE_NAME --login)
#      and re-run. We accept it here verbatim.
#
#   2. Key-file mint (default). Works on instances where the client-grant
#      already exists. Retried because a freshly-granted instance still
#      needs a short while for the grant to propagate.
if [[ -n "${PULSAR_TOKEN:-}" ]]; then
  # `snctl auth get-token --login` interleaves a browser-launch banner with
  # the token on stdout (only a still-cached session emits the bare token),
  # so $(...) capture is usually banner + token. Extract the JWT defensively
  # rather than requiring PULSAR_TOKEN to *start* with eyJ — three
  # base64url segments separated by dots; take the last match.
  PT=$(printf '%s' "$PULSAR_TOKEN" | grep -oE 'eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+' | tail -1)
  [[ -n "$PT" ]] || fail "PULSAR_TOKEN is set but no JWT (eyJ...........) found in it. Mint with: snctl -O $ORG auth get-token $INSTANCE_NAME --login (complete the browser auth; pass the whole output or just the token line)"
  ok "Using operator-supplied PULSAR_TOKEN (JWT extracted; key-file mint bypassed)"
  export TF_VAR_pulsar_token="$PT"
else
  attempt=1
  until PT=$(snctl -O "$ORG" auth get-token "$INSTANCE_NAME" \
          --key-file "$TF_DIR/streamnative-key.json" 2>/dev/null) \
        && [[ "$PT" == eyJ* ]]; do
    warn "Instance token not available yet (attempt $attempt/30) — snctl auth get-token rejected for $INSTANCE_NAME; retrying in 60s... (if this is a brand-new instance the client-grant may be missing — see PULSAR_TOKEN override above)"
    attempt=$(( attempt + 1 ))
    [[ $attempt -gt 30 ]] && fail "Could not mint a Pulsar token for $INSTANCE_NAME after 30 attempts (~30 min). Likely a missing Auth0 client-grant for this SA's client on the instance. Bypass with: export PULSAR_TOKEN=\$(snctl -O $ORG auth get-token $INSTANCE_NAME --login) and re-run."
    sleep 60
  done
  export TF_VAR_pulsar_token="$PT"
fi

terraform apply -auto-approve
elapsed "Terraform Step B" $PHASE5_START
ok "Pulsar resources created"

# ── Phase 6: Token export (idempotent re-export, then sanity-check) ──
# The Phase 2 export loop only runs when the cluster wasn't already up; on a
# resumed apply (CLUSTER_UP=true above), Phase 2 is skipped and any NEW apikey
# resource added since the last run (e.g. a new SA) would have its token only
# in `terraform output`, not on disk. This phase re-exports unconditionally,
# then verifies all expected tokens landed. Idempotent for repeat runs.
section "Phase 6 — Token export"
terraform output -json apikey_tokens 2>/dev/null | python3 -c "
import sys, json, os
tokens = json.load(sys.stdin)
for name, token in tokens.items():
    fname = name.replace('_', '-') + '.token'
    open(fname, 'w').write(token)
    print(f'  wrote {fname}')
" || fail "terraform output -json apikey_tokens failed — Step B didn't write the apikey resources?"
[[ -f "$TF_DIR/app.token" && -f "$TF_DIR/parcel-app.token" && -f "$TF_DIR/orchestrator-function.token" ]] \
  || fail "Token files missing after re-export — check terraform output -json apikey_tokens manually"
ok "SA tokens present (app.token, parcel-app.token, orchestrator-function.token)"
APP_TOKEN=$(cat "$TF_DIR/app.token")
OF_TOKEN=$(cat "$TF_DIR/orchestrator-function.token")

# ── Phase 7: Orchestrator deploy ──────────────────────────────────────────────
section "Phase 7 — Deploy orchestrator + selector-filter"
PHASE7_START=$(date +%s)

# pulsar-admin runs in a throwaway container — this project never requires a
# working host pulsar-admin (the Apache source checkout commonly on PATH is an
# unbuilt tree that dies with ClassNotFoundException; bootstrap.sh / local-mode
# already dockerize it). NAR + rendered-config paths live under
# /tmp/selector-filter-release and are bind-mounted at the same path so they
# resolve identically inside the container.
mkdir -p /tmp/selector-filter-release
pa() {
  docker run --rm \
    -v /tmp/selector-filter-release:/tmp/selector-filter-release:ro \
    "$PULSAR_IMAGE" \
    bin/pulsar-admin --admin-url "$ADMIN_URL" \
    --auth-plugin org.apache.pulsar.client.impl.auth.AuthenticationToken \
    --auth-params "token:${PA_AUTH_TOKEN:-$OF_TOKEN}" \
    "$@"
}
# Tenant/namespace-property admin (kafkaEntryFormat) requires a tenant-admin /
# superuser — the orchestrator-function SA ($OF_TOKEN) only has function +
# package rights and 401s ("Don't have permission to administrate resources on
# this tenant"). $TF_VAR_pulsar_token is the instance superuser token minted in
# Phase 5 (operator --login or the provisioning key). Use it for those ops.

# Set kafkaEntryFormat=pulsar_non_batched as the namespace default on public/default
# AND on every source topic in TF, so ShadowTraffic's Kafka producer entries are
# parseable by the broker-side filter. Per-topic is required (not just namespace
# default) — KoP's namespace-default propagation isn't reliable for auto-created
# topics, and the per-topic property is the deterministic switch (verified
# 2026-05-28 against the parcels demo).
for t in stock-quotes parcel-shipments parcel-scans parcel-exceptions; do
  echo "  Setting kafkaEntryFormat=pulsar_non_batched on persistent://public/default/$t..."
  curl -sf -X PUT \
    -H "Authorization: Bearer $TF_VAR_pulsar_token" \
    -H "Content-Type: application/json" \
    -d '{"kafkaEntryFormat":"pulsar_non_batched"}' \
    "$ADMIN_URL/admin/v2/persistent/public/default/$t/properties" \
    && ok "kafkaEntryFormat set on $t" \
    || warn "Could not set kafkaEntryFormat on $t (may already be set)"
done

echo "  Setting namespace-default kafkaEntryFormat on public/default..."
PA_AUTH_TOKEN="$TF_VAR_pulsar_token" pa namespaces set-property \
  --key kafkaEntryFormat --value pulsar_non_batched public/default \
  && ok "Namespace property set" \
  || warn "Could not set namespace property"

# Locate orchestrator + selector-filter NARs.
# Preferred: NARs pre-downloaded on the host (gh has private-repo auth — plain
# curl from this script does not). Mirrors the local-mode fix:
#   gh release download v$SF_VER \
#     --repo david-streamlio/broker-side-filtering-function \
#     --dir demo/local/nars --pattern '*.nar'
# Fallback: unauthenticated curl (works only if the release repo is public).
SF_VER="${SELECTOR_REL#v}"
mkdir -p /tmp/selector-filter-release
ORCH_NAR="/tmp/selector-filter-release/selector-filter-orchestrator-${SF_VER}.nar"
FILT_NAR="/tmp/selector-filter-release/selector-filter-function-${SF_VER}.nar"

# demo/local/nars relative to this script: recreate.sh lives in
# demo/infra/terraform, so ../../local/nars.
HOST_NARS="$TF_DIR/../../local/nars"
HOST_ORCH="$HOST_NARS/selector-filter-orchestrator-${SF_VER}.nar"
HOST_FILT="$HOST_NARS/selector-filter-function-${SF_VER}.nar"

if [[ -f "$HOST_ORCH" && -f "$HOST_FILT" ]]; then
  echo "  Using host-downloaded NARs from $HOST_NARS"
  cp "$HOST_ORCH" "$ORCH_NAR"
  cp "$HOST_FILT" "$FILT_NAR"
else
  echo "  Host NARs not found at $HOST_NARS — falling back to direct download (public repo only)..."
  curl -sfL -o "$ORCH_NAR" \
    "https://github.com/${SELECTOR_REPO}/releases/download/${SELECTOR_REL}/selector-filter-orchestrator-${SF_VER}.nar" \
    || fail "Failed to download orchestrator NAR. For a private repo, pre-download with: gh release download ${SELECTOR_REL} --repo ${SELECTOR_REPO} --dir demo/local/nars --pattern '*.nar'"
  curl -sfL -o "$FILT_NAR" \
    "https://github.com/${SELECTOR_REPO}/releases/download/${SELECTOR_REL}/selector-filter-function-${SF_VER}.nar" \
    || fail "Failed to download selector-filter NAR. See the gh release download hint above."
fi
ok "NARs ready"

# Upload selector-filter NAR as a Pulsar package — the orchestrator spawns
# instances of this function on demand by referencing the package URL.
# Control-plane lives under control-plane/broker-filter (see
# variables.tf:control_plane_{tenant,namespace}); the orchestrator-function SA
# is tenant-admin via pulsar_tenant.control_plane.admin_roles.
PKG_URL="function://control-plane/broker-filter/selector-filter@${SF_VER}"
echo "  Uploading selector-filter as Pulsar package ${PKG_URL}..."
pa packages upload "$PKG_URL" \
  --path "$FILT_NAR" \
  --description "selector-filter ${SELECTOR_REL}" \
  && ok "selector-filter package uploaded" \
  || warn "Package upload failed (may already exist at this version)"

# Reset path — undeploy orchestrator before recreating it.
if [[ "${RESET:-0}" == "1" ]]; then
  pa functions delete --tenant control-plane --namespace broker-filter --name orchestrator 2>/dev/null \
    && ok "Orchestrator deleted (RESET=1)" \
    || warn "Orchestrator was not running"
fi

# Deploy orchestrator function (if not already running).
FUNCS_LIST=$(pa functions list --tenant control-plane --namespace broker-filter 2>&1 || true)

if echo "$FUNCS_LIST" | grep -q "^orchestrator$"; then
  ok "Orchestrator already deployed — skipping (export RESET=1 to redeploy)"
else
  TMP_CFG="/tmp/selector-filter-release/orchestrator-config.$$.yaml"
  sed -e "s|@1.0|@${SF_VER}|g" \
      -e "s|\${PULSAR_ADMIN_URL}|${ADMIN_URL}|g" \
      -e "s|\${PULSAR_ADMIN_TOKEN}|${OF_TOKEN}|g" \
      "$TF_DIR/../pulsar-functions/orchestrator-function-config.yaml" > "$TMP_CFG"

  pa functions create \
    --function-config-file "$TMP_CFG" \
    --jar "$ORCH_NAR"

  rm -f "$TMP_CFG"
  ok "Orchestrator deployed"
fi
elapsed "Orchestrator deploy" $PHASE7_START

# ── Phase 8: Verify ───────────────────────────────────────────────────────────
section "Phase 8 — Verify"
PHASE8_START=$(date +%s)
sleep 5

ORCH_STATUS=$(curl -sf -H "Authorization: Bearer $OF_TOKEN" \
  "$ADMIN_URL/admin/v3/functions/control-plane/broker-filter/orchestrator/status" 2>&1 || true)
if echo "$ORCH_STATUS" | grep -q '"running":true'; then
  ok "Orchestrator is RUNNING"
else
  warn "Orchestrator status check inconclusive:"
  echo "$ORCH_STATUS" | head -20
fi

elapsed "Verify" $PHASE8_START

echo ""
echo -e "${GREEN}🎉 Infrastructure ready.${NC}"

# ── Generate demo/.env from the values terraform just produced ───────────────
# Every cluster/auth/topic value below is known here, so write .env directly
# instead of making the operator copy/paste. Only the ShadowTraffic license is
# not derivable — it lives in license.env (see license.env.example).
DEMO_DIR="$(cd "$TF_DIR/../.." && pwd)"
ENV_FILE="$DEMO_DIR/.env"
SERVICE_URL="$(printf '%s' "$ADMIN_URL" | sed -e 's|https://|pulsar+ssl://|' -e 's|$|:6651|')"
# Prefer the terraform output; fall back to deriving the KoP bootstrap from the
# admin host (:9093) since that output isn't always populated.
KAFKA_BOOTSTRAP="$(terraform output -raw kafka_bootstrap_url 2>/dev/null || true)"
[[ -n "$KAFKA_BOOTSTRAP" ]] || KAFKA_BOOTSTRAP="$(printf '%s' "$ADMIN_URL" | sed -e 's|https://||' -e 's|$|:9093|')"

# Don't clobber an existing .env — write a .generated sibling for review instead.
ENV_TARGET="$ENV_FILE"
if [[ -f "$ENV_FILE" ]]; then
  ENV_TARGET="$ENV_FILE.generated"
  warn "demo/.env already exists — writing $(basename "$ENV_TARGET") instead (review, then rename over .env to use it)"
fi

cat > "$ENV_TARGET" <<EOF
# Generated by recreate.sh ($(date -u +%Y-%m-%dT%H:%M:%SZ)) — cluster=$PULSAR_CLUSTER org=$ORG
# Cluster/auth/topic values are filled in from terraform. The ShadowTraffic
# license is NOT here — add it in license.env (see license.env.example).
PULSAR_SERVICE_URL=$SERVICE_URL
PULSAR_ADMIN_URL=$ADMIN_URL
KAFKA_BOOTSTRAP=$KAFKA_BOOTSTRAP

# Stock demo SDK credentials (docker-compose.yml reads these)
KAFKA_USERNAME=${PULSAR_CLUSTER}-app
DEMO_SA_PRINCIPAL=${PULSAR_CLUSTER}-app@${ORG}.auth.streamnative.cloud
PULSAR_TOKEN_PATH=$TF_DIR/app.token

# Parcels demo SDK credentials (docker-compose.parcels.yml reads these)
PARCEL_KAFKA_USERNAME=parcel-demo-app
PARCEL_DEMO_SA_PRINCIPAL=parcel-demo-app@${ORG}.auth.streamnative.cloud
PARCEL_PULSAR_TOKEN_PATH=$TF_DIR/parcel-app.token

# Observability container token — needs read access to
# control-plane/broker-filter/orchestrator-state (the UI's source of truth)
# and to list spawned filters under control-plane/broker-filter. Neither SDK
# SA has that scope; only the orchestrator-function SA is tenant-admin of
# control-plane. Both compose files mount this same token for observability.
ORCHESTRATOR_PULSAR_TOKEN_PATH=$TF_DIR/orchestrator-function.token

# Data topics — both demos share public/default for KoP's default kafkaNamespace
DEMO_SOURCE_TOPIC_STOCKS=persistent://public/default/stock-quotes
DEMO_SOURCE_TOPIC_SHIPMENTS=persistent://public/default/parcel-shipments
DEMO_SOURCE_TOPIC_SCANS=persistent://public/default/parcel-scans
DEMO_SOURCE_TOPIC_EXCEPTIONS=persistent://public/default/parcel-exceptions
DEMO_SOURCE_PARTITIONS=1

# Control plane — orchestrator + filter-requests + orchestrator-state live in
# control-plane/broker-filter (locked-down tenant; orchestrator-function SA is
# the only tenant admin, SDK SAs have explicit per-topic grants on filter-requests).
DEMO_CONTROL_TOPIC=persistent://control-plane/broker-filter/filter-requests
STATE_TOPIC=persistent://control-plane/broker-filter/orchestrator-state
ORCHESTRATOR_TENANT=control-plane
ORCHESTRATOR_NAMESPACE=broker-filter
ORCHESTRATOR_FUNCTION=orchestrator
HEARTBEAT_MAX_STALE_SECONDS=90
SELECTOR_REL=$SELECTOR_REL
OBSERVABILITY_IMAGE_TAG=0.1.2
EOF
ok "Wrote demo/${ENV_TARGET#$DEMO_DIR/} (cluster + auth + topics populated)"

echo ""
echo "Next steps:"
echo "  - cp $DEMO_DIR/license.env.example $DEMO_DIR/license.env   # add your ShadowTraffic LICENSE_* values"
echo "  - make demo-cloud        # from the repo root (or: make demo-cloud-parcels)"
