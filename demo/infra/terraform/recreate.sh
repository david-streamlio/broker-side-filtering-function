#!/usr/bin/env bash
#
# One-shot bring-up for the stock-quote demo's SN Cloud infrastructure.
#
# Phases:
#   0  pre-flight (env + tooling)
#   1  status check (is the cluster already up?)
#   2  Terraform Step A — instance, cluster, SAs, apikeys
#   3  wait for cluster admin endpoint
#   4  clear stale pulsar-provider state (after first apply)
#   5  Terraform Step B — tenant, namespaces, topics, permissions
#   6  export SA tokens to disk (app.token, orchestrator-function.token)
#   7  upload selector-filter NAR + deploy orchestrator function
#   8  verify
#
# Required env:
#   ORG               SN Cloud organization id (e.g. o-mj3r8)
#   SELECTOR_REPO     GitHub repo to download orchestrator + filter NARs from
#                     (default: david-streamlio/broker-side-filtering-function)
#   SELECTOR_REL      Release tag (default: v1.0.0-rc3)
#
# Optional env:
#   PULSAR_ADMIN      path to pulsar-admin (default: pulsar-admin)
#   PULSAR_CLUSTER    cluster name (default: stock-demo — matches variables.tf)
#   RESET=1           undeploy the orchestrator before re-running Phase 7

set -euo pipefail

# ── Helpers ───────────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
section() { echo -e "\n${BLUE}=== $* ===${NC}"; }
ok()      { echo -e "  ${GREEN}✓${NC} $*"; }
warn()    { echo -e "  ${YELLOW}!${NC} $*"; }
fail()    { echo -e "  ${RED}✗${NC} $*"; exit 1; }
elapsed() { local label="$1" start="$2"; printf "  ${BLUE}⏱${NC}  %s: %ds\n" "$label" $(( $(date +%s) - start )); }

TF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$TF_DIR"

PULSAR_ADMIN="${PULSAR_ADMIN:-pulsar-admin}"
PULSAR_CLUSTER="${PULSAR_CLUSTER:-stock-demo}"
SELECTOR_REPO="${SELECTOR_REPO:-david-streamlio/broker-side-filtering-function}"
SELECTOR_REL="${SELECTOR_REL:-v1.0.0-rc3}"

# ── Phase 0: Pre-flight ───────────────────────────────────────────────────────
section "Phase 0 — Pre-flight"

[[ -n "${ORG:-}" ]]                             || fail "ORG env var not set — export ORG=<your-sn-cloud-org-id>"
[[ -f "$TF_DIR/streamnative-key.json" ]]        || fail "streamnative-key.json not found in $TF_DIR (download from SN Cloud console)"
command -v "$PULSAR_ADMIN" > /dev/null 2>&1     || fail "pulsar-admin not found — set PULSAR_ADMIN or add to PATH"
command -v curl   > /dev/null 2>&1              || fail "curl not found"
command -v terraform > /dev/null 2>&1           || fail "terraform not found"
command -v python3   > /dev/null 2>&1           || fail "python3 not found (used to parse terraform JSON output)"

APP_TOKEN=""
OF_TOKEN=""
[[ -f "$TF_DIR/app.token" ]]                   && APP_TOKEN=$(cat "$TF_DIR/app.token")
[[ -f "$TF_DIR/orchestrator-function.token" ]] && OF_TOKEN=$(cat "$TF_DIR/orchestrator-function.token")

# The SA in the key file is bound to the cluster (permissions.tf
# streamnative_service_account_binding.provisioner) so it gets an Auth0
# client-grant for the instance — Phase 5's `snctl auth get-token` needs that
# grant to mint the Step B token. Derive the SA name from client_email.
PROVISIONER_SA=$(python3 -c "import json;print(json.load(open('$TF_DIR/streamnative-key.json'))['client_email'].split('@')[0])" 2>/dev/null) \
  || fail "could not parse client_email from streamnative-key.json"
[[ -n "$PROVISIONER_SA" ]] || fail "empty SA name parsed from streamnative-key.json client_email"
export TF_VAR_provisioner_sa_name="$PROVISIONER_SA"

ok "All required artifacts present (provisioning SA: $PROVISIONER_SA; SA tokens generated by Phase 2 if missing)"

# ── Phase 1: Status check ─────────────────────────────────────────────────────
section "Phase 1 — Status check"
PHASE1_START=$(date +%s)

CLUSTER_UP=false
ADMIN_URL=$(terraform output -raw pulsar_web_service_url 2>/dev/null || true)

if [[ -n "$ADMIN_URL" && -n "$OF_TOKEN" ]] && curl -sf --max-time 10 "$ADMIN_URL/admin/v2/clusters" \
    -H "Authorization: Bearer $OF_TOKEN" > /dev/null 2>&1; then
  CLUSTER_UP=true
  ok "Cluster responding at $ADMIN_URL"
elif [[ -z "$OF_TOKEN" ]]; then
  warn "No SA tokens yet — first run, will bootstrap via Terraform Step A"
else
  warn "Cluster not responding — will recreate"
fi
elapsed "Status check" $PHASE1_START

# ── Phase 2: Terraform Step A ─────────────────────────────────────────────────
if [[ "$CLUSTER_UP" == "false" ]]; then
  section "Phase 2 — Terraform Step A (instance, cluster, SAs, apikeys)"
  PHASE2_START=$(date +%s)

  echo "  Running terraform init…"
  terraform init -input=false 2>&1 | tail -5 || fail "terraform init failed"

  TF_TARGETS=(
    -target=streamnative_pulsar_instance.stock_demo
    -target=streamnative_pulsar_cluster.stock_demo
    -target=data.streamnative_pulsar_instance.stock_demo
    -target=data.streamnative_pulsar_cluster.stock_demo
    -target=streamnative_service_account.stock_demo_app
    -target=streamnative_service_account.orchestrator_function
    -target=streamnative_service_account_binding.stock_demo_app
    -target=streamnative_service_account_binding.orchestrator_function
    -target=streamnative_service_account_binding.provisioner
    -target=streamnative_apikey.stock_demo_app
    -target=streamnative_apikey.orchestrator_function
    -target=streamnative_rolebinding.stock_demo_app_consumer_group_reader
  )

  # Serverless instance/cluster provisioning takes ~10-15 min. The provider
  # returns CONTINUE_RETRY_READ_PULSAR_INSTANCE / "cluster not found" fast
  # (it exhausts its own internal poll budget and errors rather than
  # blocking), so each attempt is short — the loop, not the provider, is
  # what actually waits out provisioning. 30 attempts * 60s = ~30 min ceiling.
  attempt=1
  until terraform apply -auto-approve "${TF_TARGETS[@]}" 2>&1; do
    warn "Instance/cluster still provisioning (attempt $attempt/30) — retrying in 60s…"
    attempt=$(( attempt + 1 ))
    [[ $attempt -gt 30 ]] && fail "Instance/cluster not queryable after 30 attempts (~30 min) — check the SN Cloud console for the stock-demo instance state"
    sleep 60
  done
  elapsed "Terraform Step A" $PHASE2_START
  ok "Cluster + service accounts + apikeys created"

  # Save API key tokens to files for later phases.
  terraform output -json apikey_tokens | python3 -c "
import sys, json
tokens = json.load(sys.stdin)
for name, token in tokens.items():
    fname = name.replace('_', '-') + '.token'
    open(fname, 'w').write(token)
    print(f'  wrote {fname}')
"
  APP_TOKEN=$(cat "$TF_DIR/app.token")
  OF_TOKEN=$(cat "$TF_DIR/orchestrator-function.token")

  # ── Phase 3: Wait for cluster ──────────────────────────────────────────────
  section "Phase 3 — Wait for cluster admin endpoint"
  PHASE3_START=$(date +%s)
  ADMIN_URL=$(terraform output -raw pulsar_web_service_url)
  echo "  URL: $ADMIN_URL"
  until curl -sf --max-time 5 "$ADMIN_URL/admin/v2/clusters" \
      -H "Authorization: Bearer $OF_TOKEN" > /dev/null 2>&1; do
    printf "."
    sleep 5
  done
  echo ""
  elapsed "Cluster ready" $PHASE3_START
  ok "Cluster responding"

  # ── Phase 4: Clear stale Pulsar terraform state ────────────────────────────
  section "Phase 4 — Clear stale Pulsar state"
  PULSAR_RESOURCES=(
    pulsar_tenant.stock_demo
    pulsar_namespace.filtering
    pulsar_topic.stock_quotes
    pulsar_topic.filter_requests
    pulsar_topic.orchestrator_state
    pulsar_permission_grant.app_public_default
    pulsar_permission_grant.app_filter_requests
    pulsar_permission_grant.orchestrator_filter_deploy
    pulsar_permission_grant.orchestrator_consume_control
    pulsar_permission_grant.orchestrator_state_consume
    pulsar_permission_grant.orchestrator_state_produce
    pulsar_permission_grant.orchestrator_consume_source
    pulsar_permission_grant.orchestrator_produce_output
  )
  for r in "${PULSAR_RESOURCES[@]}"; do
    terraform state rm "$r" 2>/dev/null && echo "  removed: $r" || echo "  skipped: $r"
  done
  ok "Stale Pulsar state cleared"
else
  ok "Cluster already up — skipping Phases 2-4 (provisioning + stale-state clear)"
fi

# ── Phase 5: Terraform Step B ────────────────────────────────────────────────
# ALWAYS runs — deliberately OUTSIDE the CLUSTER_UP gate. Step B is fully
# idempotent (`terraform apply` reconciles tenant/namespaces/topics/permissions
# and is a no-op when they already exist). Keeping it gated meant a partial run
# that died after Phase 4 but before Step B left the cluster
# provisioned-but-empty, and the re-run then skipped Step B entirely because
# the cluster now reports "up".
section "Phase 5 — Terraform Step B (tenant, namespaces, topics, permissions)"
PHASE5_START=$(date +%s)

# Instance name is deterministic: main.tf sets name = "${var.cluster_name}-instance".
# Don't round-trip through `terraform output -json pulsar_instance` — a targeted
# Phase-2 apply doesn't persist that output, so it returns {} and the old
# python parse died with KeyError: 'value'.
INSTANCE_NAME="${TF_VAR_cluster_name:-stock-demo}-instance"

export TF_VAR_pulsar_web_service_url="$ADMIN_URL"

# Ensure the provisioning SA is bound to the cluster BEFORE minting its
# instance token. This creates the Auth0 client-grant for
# urn:sn:pulsar:$ORG:$INSTANCE_NAME — without it `snctl auth get-token`
# returns access_denied forever. Targeted apply uses the streamnative
# control-plane provider (key-file auth, no instance token) so there is no
# chicken-and-egg. Idempotent: a no-op when Phase 2 already created it on the
# fresh-cluster path; the work that matters on the cluster-already-up path.
if [[ -n "${TF_VAR_provisioner_sa_name:-}" ]]; then
  echo "  Ensuring provisioning SA '$TF_VAR_provisioner_sa_name' is cluster-bound (creates the Auth0 client-grant)…"
  terraform apply -auto-approve -target=streamnative_service_account_binding.provisioner \
    || fail "failed to bind provisioning SA to the cluster (streamnative provider — check streamnative-key.json rights)"
fi

# Even with the binding in place, SN Cloud's auth server needs a short while
# to propagate the new client-grant before it will mint the instance-scoped
# token — until then `snctl auth get-token` still returns access_denied /
# "could not exchange client credentials". The old `export VAR=$(snctl …)`
# form also swallowed snctl's non-zero exit, stuffing the error string into
# the token (=> uniform 401 on every Step B op). Retry until a real JWT
# comes back.
attempt=1
until PULSAR_TOKEN=$(snctl -O "$ORG" auth get-token "$INSTANCE_NAME" \
        --key-file "$TF_DIR/streamnative-key.json" 2>/dev/null) \
      && [[ "$PULSAR_TOKEN" == eyJ* ]]; do
  warn "Instance auth not propagated yet (attempt $attempt/30) — snctl auth get-token rejected for $INSTANCE_NAME; retrying in 60s…"
  attempt=$(( attempt + 1 ))
  [[ $attempt -gt 30 ]] && fail "Could not mint a Pulsar token for $INSTANCE_NAME after 30 attempts (~30 min). The provisioner binding should have created the client-grant — check it exists and that '$TF_VAR_provisioner_sa_name' is bound: snctl -O $ORG auth get-token $INSTANCE_NAME --key-file streamnative-key.json (expect a JWT, not access_denied)"
  sleep 60
done
export TF_VAR_pulsar_token="$PULSAR_TOKEN"

terraform apply -auto-approve
elapsed "Terraform Step B" $PHASE5_START
ok "Pulsar resources created"

# ── Phase 6: Token export (already done above on first run; re-export for safety) ──
section "Phase 6 — Token export"
[[ -f "$TF_DIR/app.token" && -f "$TF_DIR/orchestrator-function.token" ]] \
  || fail "Token files missing — re-run with the cluster up to regenerate"
ok "SA tokens present (app.token, orchestrator-function.token)"
APP_TOKEN=$(cat "$TF_DIR/app.token")
OF_TOKEN=$(cat "$TF_DIR/orchestrator-function.token")

# ── Phase 7: Orchestrator deploy ──────────────────────────────────────────────
section "Phase 7 — Deploy orchestrator + selector-filter"
PHASE7_START=$(date +%s)

# Set kafkaEntryFormat=pulsar_non_batched as the namespace default on public/default
# so spawned filter functions can decode Kafka-produced records, AND on the
# stock-quotes source topic so ShadowTraffic's Kafka producer entries are
# parseable by the broker-side filter.
echo "  Setting kafkaEntryFormat=pulsar_non_batched on persistent://public/default/stock-quotes…"
curl -sf -X PUT \
  -H "Authorization: Bearer $OF_TOKEN" \
  -H "Content-Type: application/json" \
  -d '{"kafkaEntryFormat":"pulsar_non_batched"}' \
  "$ADMIN_URL/admin/v2/persistent/public/default/stock-quotes/properties" \
  && ok "kafkaEntryFormat set on source topic" \
  || warn "Could not set kafkaEntryFormat (may already be set)"

echo "  Setting namespace-default kafkaEntryFormat on public/default…"
"$PULSAR_ADMIN" --admin-url "$ADMIN_URL" \
  --auth-plugin org.apache.pulsar.client.impl.auth.AuthenticationToken \
  --auth-params "token:$OF_TOKEN" \
  namespaces set-property --key kafkaEntryFormat --value pulsar_non_batched \
  public/default \
  && ok "Namespace property set" \
  || warn "Could not set namespace property"

# Locate orchestrator + selector-filter NARs.
# Preferred: NARs pre-downloaded on the host (gh has private-repo auth — plain
# curl from this script does not). Mirrors the local-mode fix:
#   gh release download v$SF_VER \
#     --repo david-streamlio/broker-side-filtering-function \
#     --dir demo/local/nars --pattern '*.nar'
# Fallback: unauthenticated curl (works only if the release repo is public).
SF_VER="${SELECTOR_REL#v}"
mkdir -p /tmp/selector-filter-release
ORCH_NAR="/tmp/selector-filter-release/selector-filter-orchestrator-${SF_VER}.nar"
FILT_NAR="/tmp/selector-filter-release/selector-filter-function-${SF_VER}.nar"

# demo/local/nars relative to this script: recreate.sh lives in
# demo/infra/terraform, so ../../local/nars.
HOST_NARS="$TF_DIR/../../local/nars"
HOST_ORCH="$HOST_NARS/selector-filter-orchestrator-${SF_VER}.nar"
HOST_FILT="$HOST_NARS/selector-filter-function-${SF_VER}.nar"

if [[ -f "$HOST_ORCH" && -f "$HOST_FILT" ]]; then
  echo "  Using host-downloaded NARs from $HOST_NARS"
  cp "$HOST_ORCH" "$ORCH_NAR"
  cp "$HOST_FILT" "$FILT_NAR"
else
  echo "  Host NARs not found at $HOST_NARS — falling back to direct download (public repo only)…"
  curl -sfL -o "$ORCH_NAR" \
    "https://github.com/${SELECTOR_REPO}/releases/download/${SELECTOR_REL}/selector-filter-orchestrator-${SF_VER}.nar" \
    || fail "Failed to download orchestrator NAR. For a private repo, pre-download with: gh release download ${SELECTOR_REL} --repo ${SELECTOR_REPO} --dir demo/local/nars --pattern '*.nar'"
  curl -sfL -o "$FILT_NAR" \
    "https://github.com/${SELECTOR_REPO}/releases/download/${SELECTOR_REL}/selector-filter-function-${SF_VER}.nar" \
    || fail "Failed to download selector-filter NAR. See the gh release download hint above."
fi
ok "NARs ready"

# Upload selector-filter NAR as a Pulsar package — the orchestrator spawns
# instances of this function on demand by referencing the package URL.
PKG_URL="function://stock-demo/filtering/selector-filter@${SF_VER}"
echo "  Uploading selector-filter as Pulsar package ${PKG_URL}…"
"$PULSAR_ADMIN" --admin-url "$ADMIN_URL" \
  --auth-plugin org.apache.pulsar.client.impl.auth.AuthenticationToken \
  --auth-params "token:$OF_TOKEN" \
  packages upload "$PKG_URL" \
  --path "$FILT_NAR" \
  --description "selector-filter ${SELECTOR_REL}" \
  && ok "selector-filter package uploaded" \
  || warn "Package upload failed (may already exist at this version)"

# Reset path — undeploy orchestrator before recreating it.
if [[ "${RESET:-0}" == "1" ]]; then
  "$PULSAR_ADMIN" --admin-url "$ADMIN_URL" \
    --auth-plugin org.apache.pulsar.client.impl.auth.AuthenticationToken \
    --auth-params "token:$OF_TOKEN" \
    functions delete --tenant stock-demo --namespace filtering --name orchestrator 2>/dev/null \
    && ok "Orchestrator deleted (RESET=1)" \
    || warn "Orchestrator was not running"
fi

# Deploy orchestrator function (if not already running).
FUNCS_LIST=$("$PULSAR_ADMIN" --admin-url "$ADMIN_URL" \
  --auth-plugin org.apache.pulsar.client.impl.auth.AuthenticationToken \
  --auth-params "token:$OF_TOKEN" \
  functions list --tenant stock-demo --namespace filtering 2>&1 || true)

if echo "$FUNCS_LIST" | grep -q "^orchestrator$"; then
  ok "Orchestrator already deployed — skipping (export RESET=1 to redeploy)"
else
  TMP_CFG=$(mktemp -t orchestrator-XXXXXX.yaml)
  sed -e "s|@1.0|@${SF_VER}|g" \
      -e "s|\${PULSAR_ADMIN_URL}|${ADMIN_URL}|g" \
      -e "s|\${PULSAR_ADMIN_TOKEN}|${OF_TOKEN}|g" \
      "$TF_DIR/../pulsar-functions/orchestrator-function-config.yaml" > "$TMP_CFG"

  "$PULSAR_ADMIN" --admin-url "$ADMIN_URL" \
    --auth-plugin org.apache.pulsar.client.impl.auth.AuthenticationToken \
    --auth-params "token:$OF_TOKEN" \
    functions create \
    --function-config-file "$TMP_CFG" \
    --jar "$ORCH_NAR"

  rm -f "$TMP_CFG"
  ok "Orchestrator deployed"
fi
elapsed "Orchestrator deploy" $PHASE7_START

# ── Phase 8: Verify ───────────────────────────────────────────────────────────
section "Phase 8 — Verify"
PHASE8_START=$(date +%s)
sleep 5

ORCH_STATUS=$(curl -sf -H "Authorization: Bearer $OF_TOKEN" \
  "$ADMIN_URL/admin/v3/functions/stock-demo/filtering/orchestrator/status" 2>&1 || true)
if echo "$ORCH_STATUS" | grep -q '"running":true'; then
  ok "Orchestrator is RUNNING"
else
  warn "Orchestrator status check inconclusive:"
  echo "$ORCH_STATUS" | head -20
fi

elapsed "Verify" $PHASE8_START

echo ""
echo -e "${GREEN}🎉 Infrastructure ready.${NC}"
echo "Next steps:"
echo "  - cp ../.env.example ../.env  (and fill in values)"
echo "  - cd ..  &&  docker compose up --build"
echo ""
echo "Key values you'll need for .env:"
echo "  PULSAR_ADMIN_URL=$ADMIN_URL"
echo "  PULSAR_SERVICE_URL=$(echo $ADMIN_URL | sed -e 's|https://|pulsar+ssl://|' -e 's|$|:6651|')"
echo "  KAFKA_BOOTSTRAP=$(terraform output -raw kafka_bootstrap_url 2>/dev/null || echo '<unset>')"
echo "  KAFKA_USERNAME=${PULSAR_CLUSTER}-app"
echo "  PULSAR_TOKEN_PATH=$TF_DIR/app.token"
echo "  DEMO_SA_PRINCIPAL=${PULSAR_CLUSTER}-app@${ORG}.auth.streamnative.cloud"
echo "  STATE_TOPIC=persistent://stock-demo/filtering/orchestrator-state"
echo "  ORCHESTRATOR_TENANT=stock-demo"
echo "  ORCHESTRATOR_NAMESPACE=filtering"
